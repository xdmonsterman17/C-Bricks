def functions():
    s = Suite("functions", "Functions")
    fn = s.b("function", {"name": "add", "returns": "int", "params": [["int", "a"], ["int", "b"]]}, top=False)
    ret = s.b("return", {"gives": "A value"}, {"value": {"type": "int", "value": "a + b"}}, top=False)
    s.link(fn, "out", [ret])
    ear = s.b("function", {"name": "early", "returns": "void", "params": [["int", "n"]]}, top=False)
    cond = s.b("if", {"operator": ">"}, {"a": V("n"), "b": I(0)}, top=False)
    s.link(cond, "true", [s.b("return", {"gives": "Nothing"}, top=False)])
    s.link(ear, "out", [cond, s.say("return.Nothing", "not reached", top=False, expect=False)])
    s.b("call", {"function": "add"}, {"a": I(2), "b": I(3)}, {"result": "sum"})
    s.out("call", V("sum"), "5")
    s.b("call", {"function": "early"}, {"n": I(1)})
    s.say("return.Nothing", "left the function early")
    # (params are [type, name] in older files; the editor writes [name, type])
    for n in s.nodes:
        if n["type"] == "function":
            n["fields"]["params"] = [[p[1], p[0]] for p in n["fields"]["params"]]
    return s


def logic():
    s = Suite("logic", "Logic")
    for op, a, b, want in [("==", I(3), I(3), "true"), ("!=", I(3), I(4), "true"), ("<", I(2), I(5), "true"),
                           ("<=", I(5), I(5), "true"), (">", I(1), I(2), "false"), (">=", I(2), I(2), "true")]:
        s.b("compare", {"op": op}, {"a": a, "b": b}, {"result": "c"})
        s.out("compare." + op, V("c"), want)
    s.b("var", {"mode": "Set", "name": "word"}, {"value": S("same")})
    s.b("compare", {"op": "=="}, {"a": V("word"), "b": S("same")}, {"result": "c"})
    s.out("compare.text", V("c"), "true")
    for op, a, b, want in [("And", B(True), B(False), "false"), ("Or", B(True), B(False), "true"), ("Not", B(True), None, "false")]:
        args = {"a": a}
        if b:
            args["b"] = b
        s.b("logic", {"op": op}, args, {"result": "l"})
        s.out("logic." + op, V("l"), want)
    return s


