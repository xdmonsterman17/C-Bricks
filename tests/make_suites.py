def events():
    s = Suite("events", "Events")
    s.order_only = True  # (a window: frames repeat their lines)
    s.say("start", "When program starts runs main()")
    ex = s.b("exit", top=False)
    s.link(ex, "out", [s.say("exit", "When program ends runs after main", top=False, expect=False)])
    # When frame starts / ends (2026-11-07): around the world's frame, every frame of the Game loop.
    fs = s.b("frame_start", top=False)
    big = s.b("compare", {"op": ">="}, {"a": V("dt"), "b": F(0)}, {"result": "dt_ok"}, top=False)
    s.link(fs, "out", [big])
    s.link(big, "next", [s.out("frame_start", V("dt_ok"), "true", top=False)])
    fe = s.b("frame_end", top=False)
    s.link(fe, "out", [s.say("frame_end", "after the objects, before drawing", top=False)])
    s.b("window", {}, {"width": I(160), "height": I(90), "title": S("events"), "fps": I(60)})
    s.b("var", {"mode": "Set", "name": "frames"}, {"value": I(0)})
    gl = s.b("game_loop")
    add = s.b("var", {"mode": "Add", "name": "frames"}, {"value": I(1)}, top=False)
    stop = s.b("if", {"operator": "=="}, {"a": V("frames"), "b": I(3)}, top=False)
    s.link(stop, "true", [s.b("quit", {}, {"code": I(0)}, top=False)])
    s.link(gl, "frame", [add, stop])
    s.lines.append("[exit] When program ends runs after main")
    return s


def flow():
    s = Suite("flow", "Flow")
    for op, a, b, want in [(">", I(5), I(3), True), ("==", S("cat"), S("cat"), True), ("!=", I(1), I(2), True),
                           ("<", I(3), I(2), False), ("<=", I(2), I(2), True), (">=", I(1), I(5), False)]:
        i = s.b("if", {"operator": op}, {"a": a, "b": b})
        s.link(i, "true", [s.say("if." + op, "true", top=False, expect=want)])
        s.link(i, "false", [s.say("if." + op, "false", top=False, expect=not want)])
    for op, a, want in [("is true", B(True), True), ("is false", B(False), True)]:
        i = s.b("if", {"operator": op}, {"a": a})
        s.link(i, "true", [s.say("if." + op, "true", top=False)])
    s.b("var", {"mode": "Set", "name": "n"}, {"value": I(0)})
    w = s.b("while", {"operator": "<"}, {"a": V("n"), "b": I(3)})
    s.link(w, "loop", [s.b("var", {"mode": "Add", "name": "n"}, {"value": I(1)}, top=False)])
    s.out("while", V("n"), "3")
    s.b("var", {"mode": "Set", "name": "total"}, {"value": I(0)})
    f = s.b("for", {}, {"from": I(0), "to": I(5), "step": I(2)}, {"index": "i"})
    s.link(f, "loop", [s.b("var", {"mode": "Add", "name": "total"}, {"value": V("i")}, top=False)])
    s.out("for", V("total"), "6")
    s.b("var", {"mode": "Set", "name": "rounds"}, {"value": I(0)})
    r = s.b("repeat", {}, {"times": I(3)}, {"counter": "c"})
    s.link(r, "loop", [s.b("var", {"mode": "Add", "name": "rounds"}, {"value": I(1)}, top=False), s.b("var", {"mode": "Set", "name": "last_c"}, {"value": V("c")}, top=False)])
    s.out("repeat", V("rounds"), "3")
    s.out("repeat.counter", V("last_c"), "2")
    s.b("var", {"mode": "Set", "name": "b_sum"}, {"value": I(0)})
    f = s.b("for", {}, {"from": I(0), "to": I(10), "step": I(1)}, {"index": "j"})
    stop = s.b("if", {"operator": "=="}, {"a": V("j"), "b": I(3)}, top=False)
    s.link(stop, "true", [s.b("break", top=False)])
    s.link(f, "loop", [stop, s.b("var", {"mode": "Add", "name": "b_sum"}, {"value": V("j")}, top=False)])
    s.out("break", V("b_sum"), "3")
    s.b("var", {"mode": "Set", "name": "c_sum"}, {"value": I(0)})
    f = s.b("for", {}, {"from": I(0), "to": I(5), "step": I(1)}, {"index": "k"})
    skip = s.b("if", {"operator": "=="}, {"a": V("k"), "b": I(2)}, top=False)
    s.link(skip, "true", [s.b("continue", top=False)])
    s.link(f, "loop", [skip, s.b("var", {"mode": "Add", "name": "c_sum"}, {"value": V("k")}, top=False)])
    s.out("continue", V("c_sum"), "8")
    rr = s.b("reroute")
    s.link(rr, "next", [s.say("reroute", "passed through", top=False)])
    s.b("list", {"op": "Make", "of": "int"}, {}, {"result": "items"})
    s.b("list", {"op": "Add"}, {"list": V("items"), "value": I(4)})
    s.b("list", {"op": "Add"}, {"list": V("items"), "value": I(5)})
    s.b("var", {"mode": "Set", "name": "fe_sum"}, {"value": I(0)})
    fe = s.b("for_each", {}, {"list": V("items")}, {"item": "it", "index": "ix"})
    s.link(fe, "loop", [s.b("var", {"mode": "Add", "name": "fe_sum"}, {"value": V("it")}, top=False), s.b("var", {"mode": "Set", "name": "fe_ix"}, {"value": V("ix")}, top=False)])
    s.out("for_each", V("fe_sum"), "9")
    s.out("for_each.index", V("fe_ix"), "1")
    for value, want in [("b", "case b"), ("zz", "default")]:
        s.b("var", {"mode": "Set", "name": "pick_" + value}, {"value": S(value)})
        sw = s.b("switch", {"cases": ["a", "b", "c"]}, {"value": V("pick_" + value)})
        s.link(sw, "case_1", [s.say("switch." + value, "case b", top=False, expect=want == "case b")])
        s.link(sw, "default", [s.say("switch." + value, "default", top=False, expect=want == "default")])
    s.b("wait", {}, {"seconds": F(0.05)})
    s.say("wait", "after 0.05 s")
    s.b("var", {"mode": "Set", "name": "pause"}, {"value": F(0.02)})
    s.b("wait", {}, {"seconds": V("pause")})
    s.say("wait.variable", "after a variable's seconds")
    return s


