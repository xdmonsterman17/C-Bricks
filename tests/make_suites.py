# Generates tests/suites/<group>/: one test project per palette group, using every brick of
# the group and every mode of every family brick, each result printed on a labelled line
# ("[text.Upper case] MIXED"), with the expected output written into its case.cfg.
#   python3 tests/make_suites.py            (all)      python3 tests/make_suites.py math text
# The runner's `coverage` check fails when a brick or a mode is missing from its group's suite.
# Behaviour that ends a program (Exit program's code, Assert failing, a wrong index...), problems
# and program flags are scenario cases in tests/cases/.
import json, os, sys, struct, zlib

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "suites")
V = lambda v: {"var": v}
I = lambda x: {"type": "int", "value": str(x)}
F = lambda x: {"type": "float", "value": str(x)}
S = lambda x: {"type": "string", "value": x}
B = lambda x: {"type": "bool", "value": "true" if x else "false"}
V3 = lambda x: {"type": "vector3", "value": x}
V2 = lambda x: {"type": "vector2", "value": x}
NONE = {"var": ""}


class Suite:
    def __init__(self, group, title):
        self.group, self.title = group, title
        self.nodes, self.n, self.main, self.lines = [], 100, [], []
        self.order_only = False      # graphics: raylib may print warnings: lines checked in order
        self.cfg = {}                # extra case.cfg keys
        self.files = {}              # extra files (path -> bytes / str)
        self.scripts = {}            # other scripts: path -> Suite-like node list

    def b(self, t, fields=None, args=None, outs=None, links=None, top=True, note=None):
        self.n += 1
        d = {"id": self.n, "type": t, "pos": [0, 0], "size": [0, 0], "fields": fields or {}, "args": args or {},
             "outs": {k: ({"var": v, "use": False} if isinstance(v, str) else v) for k, v in (outs or {}).items()}, "links": links or {}}
        if note:
            d["note"] = note
        self.nodes.append(d)
        if top:
            self.main.append(self.n)
        return self.n

    def link(self, i, group, ids):
        next(x for x in self.nodes if x["id"] == i)["links"][group] = ids

    def out(self, label, value, expect, top=True):
        """Prints "[label] <value>" (value: an input spec) and expects "[label] <expect>"."""
        f = self.b("text", {"op": "Format", "format": "[%s] {}" % label}, {"first": value}, {"result": "line_%d" % (self.n + 1)}, top=top)
        p = self.b("print", {"newline": True}, {"value": V("line_%d" % (self.n))}, top=False)
        self.link(f, "next", [p])
        self.lines.append("[%s] %s" % (label, expect))
        return f

    def say(self, label, text, top=True, expect=True):
        i = self.b("print", {"newline": True}, {"value": S("[%s] %s" % (label, text))}, top=top)
        if expect:
            self.lines.append("[%s] %s" % (label, text))
        return i

    def write(self):
        d = os.path.join(ROOT, self.group)
        os.makedirs(d, exist_ok=True)
        for f in os.listdir(d):  # a clean folder: the generator owns it
            p = os.path.join(d, f)
            if os.path.isfile(p):
                os.remove(p)
        st = {"id": 1, "type": "start", "pos": [0, 0], "size": [0, 0], "fields": {}, "args": {}, "outs": {}, "links": {"out": self.main}}
        json.dump({"format": "c-bricks", "version": 4, "next_id": self.n + 1, "nodes": [st] + self.nodes}, open(os.path.join(d, "main.cbricks"), "w"), indent="\t")
        for path, nodes in self.scripts.items():
            full = os.path.join(d, path)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            json.dump({"format": "c-bricks", "version": 4, "next_id": 1000, "nodes": nodes}, open(full, "w"), indent="\t")
        for path, data in self.files.items():
            full = os.path.join(d, path)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            open(full, "wb").write(data if isinstance(data, bytes) else data.encode())
        open(os.path.join(d, "project.cbproj"), "w").write('[project]\n\nname="Suite %s"\nversion="1.0"\n' % self.title)
        cfg = ["; The %s suite: every brick of the %s group and every mode of its family bricks," % (self.title, self.title),
               "; each printed on a labelled line. Generated by tests/make_suites.py: change it there.", "[case]"]
        for k, v in self.cfg.items():
            cfg.append("%s=%s" % (k, json.dumps(v)))
        if self.order_only:
            cfg.append("expect_order=%s" % json.dumps([l + "\n" for l in self.lines]))
        else:
            cfg.append("expect_output=%s" % json.dumps("\n".join(self.lines)))
        open(os.path.join(d, "case.cfg"), "w").write("\n".join(cfg) + "\n")


def node(i, t, fields=None, args=None, outs=None, links=None):
    return {"id": i, "type": t, "pos": [0, 0], "size": [0, 0], "fields": fields or {}, "args": args or {},
            "outs": {k: {"var": v, "use": False} for k, v in (outs or {}).items()}, "links": links or {}}


