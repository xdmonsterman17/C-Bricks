def text():
    s = Suite("text", "Text")
    cases = [("Join", {"text": S("Hello, "), "more": S("world")}, {}, "Hello, world"),
             ("Format", {"first": I(3), "second": I(5)}, {"format": "{} of {}"}, "3 of 5"),
             ("Length", {"text": S("hello")}, {}, "5"),
             ("Substring", {"text": S("hello world"), "start": I(6), "length": I(5)}, {}, "world"),
             ("Find", {"text": S("hello"), "what": S("ll")}, {}, "2"),
             ("Replace", {"text": S("a-b-c"), "what": S("-"), "with": S("+")}, {}, "a+b+c"),
             ("Upper case", {"text": S("mixed")}, {}, "MIXED"),
             ("Lower case", {"text": S("MiXeD")}, {}, "mixed"),
             ("Trim", {"text": S("  pad  ")}, {}, "pad"),
             ("Split", {"text": S("a,b,c"), "separator": S(",")}, {}, "[a, b, c]"),
             ("To text", {"value": I(42)}, {}, "42"),
             ("To int", {"text": S("42")}, {}, "42"),
             ("To float", {"text": S("2.5")}, {}, "2.5"),
             ("Starts with", {"text": S("hello"), "what": S("he")}, {}, "true"),
             ("Ends with", {"text": S("hello"), "what": S("lo")}, {}, "true")]
    for op, args, fields, want in cases:
        fl = {"op": op}
        fl.update(fields)
        out = "t_" + op.lower().replace(" ", "_")
        s.b("text", fl, args, {"result": out})
        if op == "Split":
            s.b("print", {"newline": False}, {"value": S("[text.Split] ")})
            s.b("print", {"newline": True}, {"value": V(out)})
            s.lines.append("[text.Split] " + want)
        else:
            s.out("text." + op, V(out), want)
    s.b("text", {"op": "Join list", "separator": "-"}, {"list": V("t_split"), "separator": S("-")}, {"result": "joined"})
    s.out("text.Join list", V("joined"), "a-b-c")
    return s


